import json
import argparse
from pathlib import Path


def evaluate_accuracy(generated_path: Path, expected_path: Path) -> None:
    """Evaluates accuracy of generated JSON against expected output.

    Reads both the generated results and the expected test cases. It compares
    each output sequentially to compute three primary metrics:
    Routing Accuracy (correct function name selected),
    Parameter Accuracy (correct arguments extracted),
    and Strict Accuracy (both correct without crashes).
    It prints detailed failure logs for any mismatches or engine crashes,
    followed by a final statistical summary of the run.

    Args:
        generated_path: The file path to the JSON document containing the
            outputs generated by the LLM constraint engine.
        expected_path: The file path to the JSON document containing the
            expected ground truth test cases.
    """
    generated_data = json.loads(generated_path.read_text())
    expected_data = json.loads(expected_path.read_text())
    if len(generated_data) != len(expected_data):
        print(
            f"Warning: Output count ({len(generated_data)}) does not match "
            f"expected count ({len(expected_data)})."
        )
    total_cases = len(expected_data)
    routing_correct = 0
    parameters_correct = 0
    strict_correct = 0
    errors = 0
    print("--- Evaluation Failures ---")
    for i, (gen, exp) in enumerate(zip(generated_data, expected_data)):
        prompt = exp["prompt"]
        if gen["name"] == "None":
            errors += 1
            print(f"[{i}] CRASH: {prompt}\n")
            continue
        name_match = gen.get("name") == exp.get("name")
        params_match = gen.get("parameters") == exp.get("parameters")
        if name_match:
            routing_correct += 1
        if params_match:
            parameters_correct += 1
        if name_match and params_match:
            strict_correct += 1
        else:
            print(f"[{i}] FAIL: {prompt}")
            if not name_match:
                print(f"    Expected Name : {exp.get('name')}")
                print(f"    Actual Name   : {gen.get('name')}")
            if not params_match:
                print(f"    Expected Params: {exp.get('parameters')}")
                print(f"    Actual Params  : {gen.get('parameters')}")
            print()
    print("--- Evaluation Summary ---")
    print(f"Total Test Cases   : {total_cases}")
    print(
        f"Failed / Crashed   : {errors} ({(errors / total_cases) * 100:.1f}%)"
    )
    print(
        f"Routing Accuracy   : {routing_correct} / {total_cases} "
        f"({(routing_correct / total_cases) * 100:.1f}%)"
    )
    print(
        f"Parameter Accuracy : {parameters_correct} / {total_cases} "
        f"({(parameters_correct / total_cases) * 100:.1f}%)"
    )
    print(
        f"Strict Accuracy    : {strict_correct} / {total_cases} "
        f"({(strict_correct / total_cases) * 100:.1f}%)"
    )


if __name__ == "__main__":
    description = "Evaluate LLM JSON generation accuracy."
    parser = argparse.ArgumentParser(description=description)
    help_generated = "Path to the generated results JSON file."
    parser.add_argument("--generated", required=True, help=help_generated)
    help_expected = "Path to the expected ground truth JSON file."
    parser.add_argument("--expected", required=True, help=help_expected)
    args = parser.parse_args()
    evaluate_accuracy(Path(args.generated), Path(args.expected))
